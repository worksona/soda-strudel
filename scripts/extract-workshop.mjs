// Pulls the runnable examples out of the Strudel workshop (strudel.cc/workshop)
// and writes src/workshop.js for the Examples page's Workshop tab.
// The workshop is part of Strudel (AGPL-3.0, © Strudel contributors); each
// chapter links back to its page.
//   node scripts/extract-workshop.mjs
import { writeFile } from 'node:fs/promises';

const RAW = 'https://codeberg.org/uzu/strudel/raw/branch/main/website/src/pages/workshop';
// 'motors' is left out – it drives robot hardware, not sound.
const CHAPTERS = [
  ['getting-started', 'Getting started'],
  ['first-sounds', 'First sounds'],
  ['first-notes', 'First notes'],
  ['first-effects', 'First effects'],
  ['pattern-effects', 'Pattern effects'],
  ['recap', 'Recap'],
];

const chapters = [];
for (const [slug, title] of CHAPTERS) {
  const res = await fetch(`${RAW}/${slug}.mdx`);
  if (!res.ok) throw new Error(`${slug}: ${res.status}`);
  const mdx = await res.text();
  const items = [];
  let heading = title;
  // walk the file in order: remember the latest heading, collect each tune={`…`}
  const re = /^(#{2,4})\s+(.+)$|tune=\{`((?:\\`|[^`])*)`\}/gm;
  for (const m of mdx.matchAll(re)) {
    if (m[1]) {
      heading = m[2].replace(/\*\*/g, '').replace(/`/g, '').trim();
      continue;
    }
    const code = m[3].replace(/\\`/g, '`').replace(/\\\$/g, '$').trim();
    if (!code || items.some((it) => it.code === code)) continue;
    items.push({ heading, code });
  }
  if (items.length) chapters.push({ id: slug, title, url: `https://strudel.cc/workshop/${slug}/`, items });
}

const total = chapters.reduce((n, c) => n + c.items.length, 0);
await writeFile(
  new URL('../src/workshop.js', import.meta.url),
  `// Generated by scripts/extract-workshop.mjs – do not edit by hand.
// Examples from the Strudel workshop, https://strudel.cc/workshop/
// Strudel is AGPL-3.0, © Strudel contributors.
export const WORKSHOP = ${JSON.stringify(chapters, null, 1)};
`,
);
console.log(`workshop: ${chapters.length} chapters, ${total} examples`);
