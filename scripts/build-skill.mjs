// Bundles the vibe skill's helper script (validator + link codec) into a single
// dependency-free file and copies the current catalogues next to it, so the
// skill works in Claude Code and in claude.ai's sandbox without npm install.
// SODA_SITE_URL sets the site the skill builds links for (default: localhost).
import { build } from 'esbuild';
import { copyFile, readFile, readdir, writeFile } from 'node:fs/promises';
import { zipSync } from 'fflate';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const root = new URL('../', import.meta.url);
const skill = new URL('claude/skills/strudel-vibe/', root);
const fromCore = createRequire(createRequire(import.meta.url).resolve('@strudel/core/package.json'));
const kabelsalat = join(dirname(fromCore.resolve('@kabelsalat/web/package.json')), 'dist/index.mjs');

await build({
  entryPoints: [new URL('scripts/soda-cli.mjs', root).pathname],
  outfile: new URL('scripts/soda.mjs', skill).pathname,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node18',
  mainFields: ['module', 'main'],
  alias: { '@kabelsalat/web': kabelsalat },
  banner: { js: '// Generated by scripts/build-skill.mjs from soda-strudel – do not edit. AGPL-3.0-or-later.' },
  logLevel: 'warning',
  legalComments: 'none',
});

await copyFile(new URL('public/sounds.json', root), new URL('sounds.json', skill));
await copyFile(new URL('public/media.json', root), new URL('media.json', skill));
const cfgUrl = new URL('config.json', skill);
const cfg = JSON.parse(await readFile(cfgUrl, 'utf8').catch(() => '{}'));
cfg.siteUrl = process.env.SODA_SITE_URL ?? cfg.siteUrl ?? 'http://localhost:5173';
await writeFile(cfgUrl, JSON.stringify(cfg, null, 2) + '\n');

// Zip for claude.ai (Settings › Capabilities › Skills › Upload), served by the site at /strudel-vibe.zip
async function collect(dir, prefix = 'strudel-vibe/') {
  const files = {};
  for (const e of await readdir(dir, { withFileTypes: true })) {
    if (e.name.startsWith('.')) continue;
    const url = new URL(e.name + (e.isDirectory() ? '/' : ''), dir);
    if (e.isDirectory()) Object.assign(files, await collect(url, `${prefix}${e.name}/`));
    else files[`${prefix}${e.name}`] = new Uint8Array(await readFile(url));
  }
  return files;
}
await writeFile(new URL('public/strudel-vibe.zip', root), zipSync(await collect(skill), { level: 9 }));
console.log(`skill bundled + zipped (site ${cfg.siteUrl})`);
